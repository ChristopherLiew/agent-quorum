func TestGuard(t *testing.T) {
	const stash, addAll = "git stash", "git add -A"
	tests := []struct {
		name    string
		holder  string // session that holds a claim; "" for none
		path    string
		cwd     string
		command string
		setup   func(e *fakeEnv)
		want    string
		advice  string
	}{
		{name: "rewrites tree, other holds", holder: "a", path: "/repo/f", cwd: "/repo", command: stash, setup: nil, want: proto.Deny, advice: "do not run this command; it would overwrite or hide another session's uncommitted work. Ask the user how to proceed."},
		{name: "sweeps index, other holds", holder: "a", path: "/repo/f", cwd: "/repo", command: addAll, setup: nil, want: proto.Deny, advice: "stage only your own files by explicit path: git add <paths>, and commit without -a"},
		{name: "cwd in subdir of the repo", holder: "a", path: "/repo/f", cwd: "/repo/sub", command: stash, setup: nil, want: proto.Deny, advice: ""},
		{name: "safe command", holder: "a", path: "/repo/f", cwd: "/repo", command: "git status", setup: nil, want: proto.Grant, advice: ""},
		{name: "rewrites tree, nobody holds", holder: "", path: "", cwd: "/repo", command: stash, setup: nil, want: proto.Grant, advice: ""},
		{name: "sweeps index, nobody holds", holder: "", path: "", cwd: "/repo", command: addAll, setup: nil, want: proto.Grant, advice: ""},
		{name: "only the caller holds", holder: "b", path: "/repo/f", cwd: "/repo", command: stash, setup: nil, want: proto.Grant, advice: ""},
		{name: "only the caller holds, sweep", holder: "b", path: "/repo/f", cwd: "/repo", command: addAll, setup: nil, want: proto.Grant, advice: ""},
		{name: "other's claims in a different repo", holder: "a", path: "/other/f", cwd: "/repo", command: stash, setup: nil, want: proto.Grant, advice: ""},
		{name: "cwd not in a repo", holder: "a", path: "/repo/f", cwd: "/tmp", command: stash, setup: nil, want: proto.Grant, advice: ""},
		{name: "other holder dead", holder: "a", path: "/repo/f", cwd: "/repo", command: stash, setup: func(e *fakeEnv) { e.dead[1] = true }, want: proto.Grant, advice: ""},
		{name: "other's claim stale", holder: "a", path: "/repo/f", cwd: "/repo", command: addAll, setup: func(e *fakeEnv) { e.advance(time.Hour) }, want: proto.Grant, advice: ""},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			env := newEnv()
			s := newState(env)
			switch tc.holder {
			case "a":
				do(t, s, rq(proto.OpClaim, "a", 1, tc.path))
			case "b":
				do(t, s, rq(proto.OpClaim, "b", 2, tc.path))
			}
			if tc.setup != nil {
				tc.setup(env)
			}
			g := rq(proto.OpGuard, "b", 2)
			g.CWD, g.Command = tc.cwd, tc.command
			resp := do(t, s, g)
			wantDecision(t, resp, tc.want)
			if tc.want == proto.Grant {
				return
			}
			if !strings.HasPrefix(resp.Reason, "agent-quorum: ") || !strings.Contains(resp.Reason, "claude:a") ||
				!strings.Contains(resp.Reason, tc.path) || !strings.Contains(resp.Reason, tc.advice) {
				t.Errorf("Reason = %q, want prefix %q and mention of claude:a, %s and %q", resp.Reason, "agent-quorum: ", tc.path, tc.advice)
			}
			if len(resp.Holders) != 1 || resp.Holders[0].Session != "claude:a" ||
				!reflect.DeepEqual(resp.Holders[0].Paths, []string{tc.path}) {
				t.Errorf("Holders = %+v, want claude:a holding [%s]", resp.Holders, tc.path)
			}
		})
	}
}

