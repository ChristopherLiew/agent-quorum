func TestHelloPeersAndContext(t *testing.T) {
	env := newEnv()
	s := newState(env)

	first := do(t, s, rq(proto.OpHello, "a", 1))
	if first.Context != "" || len(first.Peers) != 0 {
		t.Fatalf("lone session hello = context %q peers %v, want none", first.Context, first.Peers)
	}
	do(t, s, rq(proto.OpClaim, "a", 1, "/repo/z.go", "/repo/a.go"))
	n := rq(proto.OpNote, "a", 1)
	n.Note = "refactor auth"
	do(t, s, n)

	// Sessions elsewhere are not peers.
	o := rq(proto.OpHello, "elsewhere", 3)
	o.CWD = "/other"
	do(t, s, o)
	// A dead session is not a peer.
	do(t, s, rq(proto.OpHello, "dead", 4))
	env.dead[4] = true

	h := rq(proto.OpHello, "b", 2)
	h.CWD, h.Note = "/repo/sub", "my\ntask"
	resp := do(t, s, h)
	if len(resp.Peers) != 1 || resp.Peers[0].Session != "claude:a" ||
		!reflect.DeepEqual(resp.Peers[0].Paths, []string{"/repo/a.go", "/repo/z.go"}) || resp.Peers[0].Note != "refactor auth" {
		t.Fatalf("Peers = %+v, want claude:a holding a.go and z.go with note %q", resp.Peers, "refactor auth")
	}
	for _, sub := range []string{"claude:a", "refactor auth", "a.go, z.go", "denied by agent-quorum", "sed, redirection",
		"git add <paths>", "git add -A", "commit -a", "checkout, stash, reset --hard"} {
		if !strings.Contains(resp.Context, sub) {
			t.Errorf("Context = %q, want it to contain %q", resp.Context, sub)
		}
	}
	if utf8.RuneCountInString(resp.Context) > 600 {
		t.Errorf("len(Context) = %d chars, want <= 600", utf8.RuneCountInString(resp.Context))
	}
	st := do(t, s, proto.Request{V: proto.Version, Op: proto.OpStatus})
	for _, x := range st.Sessions {
		if x.Session == "claude:b" && x.Note != "my task" {
			t.Errorf("note of claude:b = %q, want %q", x.Note, "my task")
		}
		if x.Session == "claude:dead" {
			t.Error("status lists claude:dead, want it pruned")
		}
	}
}

