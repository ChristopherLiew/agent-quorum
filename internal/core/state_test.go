// fakeEnv is only reached through State.Handle, which serialises calls.
type fakeEnv struct {
	now      time.Time
	dead     map[int]bool    // pids not in here are alive
	dirty    map[string]bool // path -> dirty
	gitFails bool            // Dirty reports known=false
	roots    []string        // repo roots; RepoRoot returns the one containing dir
}

func newEnv() *fakeEnv {
	return &fakeEnv{
		now:   time.Date(2026, 1, 2, 3, 4, 5, 0, time.UTC),
		dead:  map[int]bool{},
		dirty: map[string]bool{},
		roots: []string{"/repo", "/other"},
	}
}

func (e *fakeEnv) Now() time.Time     { return e.now }
func (e *fakeEnv) Alive(pid int) bool { return !e.dead[pid] }
func (e *fakeEnv) Dirty(repo, path string) (bool, bool) {
	if repo == "" || e.gitFails {
		return false, false
	}
	return e.dirty[path], true
}
func (e *fakeEnv) RepoRoot(dir string) string {
	for _, r := range e.roots {
		if dir == r || strings.HasPrefix(dir, r+"/") {
			return r
		}
	}
	return ""
}
func (e *fakeEnv) advance(d time.Duration) { e.now = e.now.Add(d) }

func fakeClassify(cmd string) guard.Risk {
	switch {
	case strings.Contains(cmd, "stash"):
		return guard.RewritesTree
	case strings.Contains(cmd, "add -A"):
		return guard.SweepsIndex
	}
	return guard.None
}

func newState(env *fakeEnv) *State { return New(env, Config{Classify: fakeClassify}) }

// rq builds a request for agent "claude"; pid 0 means unknown.
func rq(op, sess string, pid int, paths ...string) proto.Request {
	return proto.Request{V: proto.Version, Op: op, Agent: "claude", Session: sess, PID: pid, CWD: "/repo", Paths: paths}
}

func do(t *testing.T, s *State, r proto.Request) proto.Response {
	t.Helper()
	resp := s.Handle(r)
	if !resp.OK {
		t.Fatalf("Handle(%s).OK = false (error %q), want true", r.Op, resp.Error)
	}
	return resp
}

func wantDecision(t *testing.T, resp proto.Response, want string) {
	t.Helper()
	if resp.Decision != want {
		t.Fatalf("decision = %q, want %q (reason %q)", resp.Decision, want, resp.Reason)
	}
}

func claimOf(s *State, path string) *Claim {
	s.mu.Lock()
	defer s.mu.Unlock()
	if c := s.claims[path]; c != nil {
		cp := *c
		return &cp
	}
	return nil
}

func TestClaimBasics(t *testing.T) {
	env := newEnv()
	s := newState(env)

	wantDecision(t, do(t, s, rq(proto.OpClaim, "a", 1, "/repo/f.go")), proto.Grant)
	c := claimOf(s, "/repo/f.go")
	if c == nil || c.Owner != "claude:a" || c.Repo != "/repo" || !c.AcquiredAt.Equal(env.now) {
		t.Fatalf("claimOf(/repo/f.go) = %+v, want owner claude:a, repo /repo, acquired now", c)
	}
	t0 := env.now

	env.advance(10 * time.Second)
	wantDecision(t, do(t, s, rq(proto.OpClaim, "a", 1, "/repo/f.go")), proto.Grant)
	c = claimOf(s, "/repo/f.go")
	if !c.TouchedAt.Equal(env.now) || !c.AcquiredAt.Equal(t0) {
		t.Fatalf("after refresh claim touched/acquired = %v/%v, want %v/%v", c.TouchedAt, c.AcquiredAt, env.now, t0)
	}

	// Empty paths grant.
	wantDecision(t, do(t, s, rq(proto.OpClaim, "b", 2)), proto.Grant)
}

func TestClaimDeniedNamesHolder(t *testing.T) {
	env := newEnv()
	s := newState(env)
	do(t, s, rq(proto.OpClaim, "9f2c", 1, "/repo/auth.go"))
	n := rq(proto.OpNote, "9f2c", 1)
	n.Note = "refactor token refresh"
	do(t, s, n)
	env.advance(40 * time.Second)

	resp := do(t, s, rq(proto.OpClaim, "b", 2, "/repo/auth.go"))
	wantDecision(t, resp, proto.Deny)
	want := `agent-quorum: /repo/auth.go is being edited by another agent session (claude:9f2c, active 40s ago, working on "refactor token refresh"). Do not edit this file and do not modify it through shell commands. Continue with work that does not need it, or ask the user how to proceed.`
	if resp.Reason != want {
		t.Errorf("reason:\n got %s\nwant %s", resp.Reason, want)
	}
	if len(resp.Holders) != 1 {
		t.Fatalf("Holders = %+v, want exactly one", resp.Holders)
	}
	h := resp.Holders[0]
	if h.Session != "claude:9f2c" || h.IdleS != 40 || h.Note != "refactor token refresh" ||
		!reflect.DeepEqual(h.Paths, []string{"/repo/auth.go"}) {
		t.Errorf("Holders[0] = %+v, want session claude:9f2c idle 40s note %q paths [/repo/auth.go]", h, "refactor token refresh")
	}
	if c := claimOf(s, "/repo/auth.go"); c.Owner != "claude:9f2c" {
		t.Errorf("owner after denied claim = %s, want claude:9f2c", c.Owner)
	}
}

func TestDenyReasonVariants(t *testing.T) {
	env := newEnv()
	s := newState(env)
	do(t, s, rq(proto.OpClaim, "a", 1, "/repo/a1", "/repo/a2"))
	do(t, s, rq(proto.OpClaim, "b", 2, "/repo/b1"))

	// One holder, no note, several paths.
	r := do(t, s, rq(proto.OpClaim, "c", 3, "/repo/a1", "/repo/a2")).Reason
	if strings.Contains(r, "working on") || !strings.Contains(r, "/repo/a1, /repo/a2 are being edited by another agent session (claude:a, active 0s ago). Do not edit these files") {
		t.Errorf("Reason = %q, want multi-path wording without a note", r)
	}
	// Several holders.
	resp := do(t, s, rq(proto.OpClaim, "c", 3, "/repo/a1", "/repo/b1", "/repo/free"))
	if len(resp.Holders) != 2 || resp.Holders[0].Session != "claude:a" || resp.Holders[1].Session != "claude:b" {
		t.Fatalf("Holders = %+v, want claude:a then claude:b", resp.Holders)
	}
	for _, sub := range []string{"agent-quorum: ", "other agent sessions", "/repo/a1 (claude:a,", "/repo/b1 (claude:b,"} {
		if !strings.Contains(resp.Reason, sub) {
			t.Errorf("Reason = %q, want it to contain %q", resp.Reason, sub)
		}
	}
	// Many paths are truncated.
	var many []string
	for i := 0; i < 9; i++ {
		many = append(many, fmt.Sprintf("/repo/m%d", i))
	}
	do(t, s, rq(proto.OpClaim, "m", 4, many...))
	if r := do(t, s, rq(proto.OpClaim, "c", 3, many...)).Reason; !strings.Contains(r, "/repo/m4 and 4 more") || strings.Contains(r, "/repo/m5") {
		t.Errorf("Reason = %q, want it to end the path list at /repo/m4 and 4 more", r)
	}
}

func TestByeFreesOnlyOwnClaims(t *testing.T) {
	env := newEnv()
	s := newState(env)
	do(t, s, rq(proto.OpClaim, "a", 1, "/repo/a1", "/repo/a2"))
	do(t, s, rq(proto.OpClaim, "b", 2, "/repo/b1"))
	do(t, s, rq(proto.OpBye, "a", 1))
	do(t, s, rq(proto.OpBye, "nobody", 0)) // unknown is fine

	if claimOf(s, "/repo/a1") != nil || claimOf(s, "/repo/a2") != nil {
		t.Error("claims of a after bye = held, want released")
	}
	if c := claimOf(s, "/repo/b1"); c == nil || c.Owner != "claude:b" {
		t.Error("claim of b after a's bye = lost, want kept")
	}
	st := do(t, s, proto.Request{V: proto.Version, Op: proto.OpStatus})
	if len(st.Sessions) != 1 || st.Sessions[0].Session != "claude:b" {
		t.Errorf("Sessions after bye = %+v, want only claude:b", st.Sessions)
	}
	wantDecision(t, do(t, s, rq(proto.OpClaim, "c", 3, "/repo/a1")), proto.Grant)
}

