func TestClaimLifecycle(t *testing.T) {
	week := 7 * 24 * time.Hour
	tests := []struct {
		name      string
		path      string
		holderPID int
		setup     func(e *fakeEnv)
		age       time.Duration
		want      string
	}{
		{name: "holder dead", path: "/repo/f", holderPID: 1, setup: func(e *fakeEnv) { e.dead[1] = true }, age: time.Second, want: proto.Grant},
		{name: "alive clean older than grace", path: "/repo/f", holderPID: 1, setup: nil, age: 121 * time.Second, want: proto.Grant},
		{name: "alive clean exactly grace", path: "/repo/f", holderPID: 1, setup: nil, age: 120 * time.Second, want: proto.Grant},
		{name: "alive clean younger than grace", path: "/repo/f", holderPID: 1, setup: nil, age: 119 * time.Second, want: proto.Deny},
		{name: "alive dirty a week old", path: "/repo/f", holderPID: 1, setup: func(e *fakeEnv) { e.dirty["/repo/f"] = true }, age: week, want: proto.Deny},
		{name: "not a git repo: liveness only", path: "/tmp/f", holderPID: 1, setup: nil, age: week, want: proto.Deny},
		{name: "not a git repo, holder dead", path: "/tmp/f", holderPID: 1, setup: func(e *fakeEnv) { e.dead[1] = true }, age: week, want: proto.Grant},
		{name: "git fails (known=false): liveness only", path: "/repo/f", holderPID: 1, setup: func(e *fakeEnv) { e.gitFails = true }, age: week, want: proto.Deny},
		{name: "pid unknown within idle ttl", path: "/tmp/f", holderPID: 0, setup: nil, age: 29 * time.Minute, want: proto.Deny},
		{name: "pid unknown past idle ttl", path: "/tmp/f", holderPID: 0, setup: nil, age: 30 * time.Minute, want: proto.Grant},
		{name: "pid unknown past idle ttl, dirty", path: "/repo/f", holderPID: 0, setup: func(e *fakeEnv) { e.dirty["/repo/f"] = true }, age: 31 * time.Minute, want: proto.Grant},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			env := newEnv()
			s := newState(env)
			do(t, s, rq(proto.OpClaim, "a", tc.holderPID, tc.path, "/repo/a-other"))
			if tc.setup != nil {
				tc.setup(env)
			}
			env.advance(tc.age)

			resp := do(t, s, rq(proto.OpClaim, "b", 2, tc.path))
			wantDecision(t, resp, tc.want)
			c := claimOf(s, tc.path)
			if tc.want == proto.Deny {
				if c.Owner != "claude:a" {
					t.Errorf("owner after denied claim = %s, want claude:a", c.Owner)
				}
				return
			}
			if c.Owner != "claude:b" || !c.AcquiredAt.Equal(env.now) || !c.TouchedAt.Equal(env.now) {
				t.Errorf("claim after takeover = %+v, want owner claude:b acquired and touched now", c)
			}
		})
	}
}

