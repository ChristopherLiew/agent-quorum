func TestCheck(t *testing.T) {
	env := newEnv()
	s := newState(env)
	do(t, s, rq(proto.OpClaim, "a", 1, "/repo/a1", "/repo/a2"))
	do(t, s, rq(proto.OpClaim, "b", 2, "/repo/b1"))
	paths := []string{"/repo/a1", "/repo/a2", "/repo/b1", "/repo/free"}

	resp := do(t, s, rq(proto.OpCheck, "b", 2, paths...))
	wantDecision(t, resp, proto.Deny)
	if len(resp.Holders) != 1 || resp.Holders[0].Session != "claude:a" ||
		!reflect.DeepEqual(resp.Holders[0].Paths, []string{"/repo/a1", "/repo/a2"}) ||
		!strings.HasPrefix(resp.Reason, "agent-quorum: ") || !strings.Contains(resp.Reason, "claude:a") {
		t.Errorf("Check(b) = %+v, want deny naming claude:a with paths a1, a2", resp)
	}
	// Anonymous requester sees every holder, and no session is created.
	resp = do(t, s, proto.Request{V: proto.Version, Op: proto.OpCheck, Paths: paths})
	if len(resp.Holders) != 2 {
		t.Errorf("len(Holders) = %d, want 2", len(resp.Holders))
	}
	do(t, s, rq(proto.OpCheck, "stranger", 7, paths...))
	if st := do(t, s, proto.Request{V: proto.Version, Op: proto.OpStatus}); len(st.Sessions) != 2 {
		t.Errorf("Sessions after check = %+v, want 2 (check must not create a session)", st.Sessions)
	}
	wantDecision(t, do(t, s, rq(proto.OpCheck, "b", 2, "/repo/b1", "/repo/free")), proto.Grant)
	// Stale claims do not block a check.
	env.advance(time.Hour)
	wantDecision(t, do(t, s, rq(proto.OpCheck, "b", 2, "/repo/a1")), proto.Grant)
	if claimOf(s, "/repo/a1") != nil {
		t.Error("stale claim after check = kept, want dropped")
	}
}

func TestStatusPrunes(t *testing.T) {
	env := newEnv()
	s := newState(env)
	do(t, s, rq(proto.OpClaim, "b", 2, "/repo/z", "/repo/dirty", "/repo/clean"))
	do(t, s, rq(proto.OpClaim, "a", 1, "/repo/a1"))
	do(t, s, rq(proto.OpClaim, "dead", 3, "/repo/d1"))
	idle := rq(proto.OpClaim, "idle", 0, "/tmp/i1")
	idle.CWD = "/tmp"
	do(t, s, idle)

	env.dirty["/repo/dirty"], env.dirty["/repo/z"], env.dirty["/repo/a1"] = true, true, true
	env.dead[3] = true
	env.advance(31 * time.Minute)

	st := do(t, s, proto.Request{V: proto.Version, Op: proto.OpStatus})
	if len(st.Sessions) != 2 {
		t.Fatalf("Sessions = %+v, want 2", st.Sessions)
	}
	a, b := st.Sessions[0], st.Sessions[1]
	if a.Session != "claude:a" || b.Session != "claude:b" {
		t.Fatalf("session order = %s, %s, want claude:a, claude:b", a.Session, b.Session)
	}
	if !reflect.DeepEqual(b.Paths, []string{"/repo/dirty", "/repo/z"}) {
		t.Errorf("b.Paths = %v, want [/repo/dirty /repo/z]", b.Paths)
	}
	if b.IdleS != 31*60 || b.PID != 2 || b.CWD != "/repo" || b.Repo != "/repo" || b.Agent != "claude" {
		t.Errorf("b = %+v, want idle 1860s pid 2 cwd and repo /repo agent claude", b)
	}
	s.mu.Lock()
	nc, ns := len(s.claims), len(s.sessions)
	s.mu.Unlock()
	if nc != 3 || ns != 2 {
		t.Errorf("after prune: %d claims, %d sessions, want 3, 2", nc, ns)
	}
}

func TestExportImportRoundTrip(t *testing.T) {
	env := newEnv()
	s := newState(env)
	h := rq(proto.OpHello, "a", 1)
	h.Note = "working"
	do(t, s, h)
	do(t, s, rq(proto.OpClaim, "a", 1, "/repo/a1", "/repo/a2"))
	env.advance(1500 * time.Millisecond)
	idle := rq(proto.OpClaim, "b", 0, "/tmp/b1")
	idle.CWD = "/tmp"
	do(t, s, idle)

	data, err := s.Export()
	if err != nil {
		t.Fatal(err)
	}
	s2 := newState(env)
	do(t, s2, rq(proto.OpClaim, "junk", 9, "/repo/junk")) // replaced by Import
	if err := s2.Import(data); err != nil {
		t.Fatal(err)
	}
	if !reflect.DeepEqual(s.sessions, s2.sessions) || !reflect.DeepEqual(s.claims, s2.claims) {
		t.Errorf("sessions after Import(Export()) = %+v, want %+v", s2.sessions, s.sessions)
	}
	data2, err := s2.Export()
	if err != nil {
		t.Fatal(err)
	}
	if string(data) != string(data2) {
		t.Errorf("second Export() = %s, want %s", data2, data)
	}
	// The imported state decides like the original.
	wantDecision(t, do(t, s2, rq(proto.OpClaim, "c", 3, "/repo/a1")), proto.Deny)

	// Empty data is a no-op; bad data is an error and changes nothing.
	for _, d := range [][]byte{nil, {}} {
		if err := s2.Import(d); err != nil {
			t.Errorf("Import(%v) = %v, want nil", d, err)
		}
	}
	if err := s2.Import([]byte("{nope")); err == nil {
		t.Error("Import(bad snapshot) = nil, want error")
	}
	if claimOf(s2, "/repo/a1") == nil {
		t.Error("state after no-op or failed Import = lost, want unchanged")
	}
	// An empty state exports and imports too.
	empty, err := newState(env).Export()
	if err != nil {
		t.Fatal(err)
	}
	if err := s2.Import(empty); err != nil || claimOf(s2, "/repo/a1") != nil {
		t.Errorf("Import(empty snapshot) = %v, claim kept = %t, want nil and dropped", err, claimOf(s2, "/repo/a1") != nil)
	}
}

