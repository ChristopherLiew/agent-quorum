// Defaults and caps. contextMax and reasonMaxFiles bound the text written for
// the model.
const (
	defaultGrace   = 120 * time.Second
	defaultIdleTTL = 30 * time.Minute
	noteMaxRunes   = 80
	contextMax     = 600 // hard cap on Response.Context, in characters
	reasonMaxFiles = 5   // files named in a deny reason before "and N more"
)

// State holds every session and claim. All access goes through Handle,
// Export and Import, each of which holds mu for the whole call (including
// any Env calls, see docs/DESIGN.md M4).
type State struct {
	mu       sync.Mutex // guards every field below, and serialises Env calls
	env      Env
	cfg      Config
	sessions map[SessionID]*Session
	claims   map[string]*Claim // keyed by cleaned absolute path
}

// New returns an empty State. Zero Config fields take their defaults.
func New(env Env, cfg Config) *State {
	if cfg.Grace <= 0 {
		cfg.Grace = defaultGrace
	}
	if cfg.IdleTTL <= 0 {
		cfg.IdleTTL = defaultIdleTTL
	}
	if cfg.Classify == nil {
		cfg.Classify = guard.Classify
	}
	return &State{
		env:      env,
		cfg:      cfg,
		sessions: map[SessionID]*Session{},
		claims:   map[string]*Claim{},
	}
}

// Handle answers one request. It is the only entry point for decisions.
func (s *State) Handle(req proto.Request) proto.Response {
	s.mu.Lock()
	defer s.mu.Unlock()

	if req.V != proto.Version {
		return fail(fmt.Sprintf("unsupported protocol version %d (want %d)", req.V, proto.Version))
	}
	id := ownerID(req)
	switch req.Op {
	case proto.OpHello, proto.OpClaim, proto.OpGuard, proto.OpNote, proto.OpBye:
		if req.Session == "" {
			return fail(req.Op + ": session is required")
		}
	}
	now := s.env.Now()

	switch req.Op {
	case proto.OpHello:
		return s.hello(id, req, now)
	case proto.OpClaim:
		return s.claim(id, req, now)
	case proto.OpGuard:
		return s.guard(id, req, now)
	case proto.OpNote:
		s.touch(id, req, now).Note = cleanNote(req.Note)
		return proto.Response{OK: true}
	case proto.OpBye:
		s.drop(id)
		return proto.Response{OK: true}
	case proto.OpRelease:
		return s.release(id, req)
	case proto.OpCheck:
		return s.check(id, req, now)
	case proto.OpStatus:
		return s.status(now)
	}
	return fail(fmt.Sprintf("unknown op %q", req.Op))
}

func fail(msg string) proto.Response { return proto.Response{OK: false, Error: msg} }

func ownerID(req proto.Request) SessionID {
	if req.Agent != "" {
		return SessionID(req.Agent + ":" + req.Session)
	}
	return SessionID(req.Session)
}

// ---- ops ----

func (s *State) hello(id SessionID, req proto.Request, now time.Time) proto.Response {
	me := s.touch(id, req, now)
	if req.Note != "" {
		me.Note = cleanNote(req.Note)
	}
	s.prune(now)

	var peers []proto.Holder
	for _, o := range s.sessions {
		if o.ID == id {
			continue
		}
		if me.Repo != "" {
			if o.Repo != me.Repo {
				continue
			}
		} else if me.CWD == "" || o.CWD != me.CWD {
			continue
		}
		peers = append(peers, s.holder(o, s.pathsOf(o.ID), now))
	}
	sortHolders(peers)
	return proto.Response{OK: true, Peers: peers, Context: peerContext(peers, me.Repo)}
}

func (s *State) claim(id SessionID, req proto.Request, now time.Time) proto.Response {
	s.touch(id, req, now)
	paths := cleanPaths(req.Paths)

	contested := map[SessionID][]string{}
	for _, p := range paths {
		if c := s.claims[p]; c != nil && c.Owner != id && s.valid(c, now) {
			contested[c.Owner] = append(contested[c.Owner], p)
		}
	}
	if len(contested) > 0 {
		hs := s.holders(contested, now)
		return proto.Response{OK: true, Decision: proto.Deny, Holders: hs, Reason: heldReason(hs,
			"is being edited", "are being edited", "the files below are being edited",
			"Do not edit this file and do not modify it through shell commands. Continue with work that does not need it, or ask the user how to proceed.",
			"Do not edit these files and do not modify them through shell commands. Continue with work that does not need them, or ask the user how to proceed.")}
	}

	// Whatever is still claimed on these paths is ours: stale claims of
	// others were deleted by valid() above.
	for _, p := range paths {
		c := s.claims[p]
		if c == nil {
			c = &Claim{Path: p, Owner: id, AcquiredAt: now}
			s.claims[p] = c
		}
		c.Repo = s.env.RepoRoot(filepath.Dir(p))
		c.TouchedAt = now
	}
	return proto.Response{OK: true, Decision: proto.Grant}
}

func (s *State) guard(id SessionID, req proto.Request, now time.Time) proto.Response {
	me := s.touch(id, req, now)
	grant := proto.Response{OK: true, Decision: proto.Grant}

	risk := s.cfg.Classify(req.Command)
	if risk == guard.None {
		return grant
	}
	repo := me.Repo // touch just set it from req.CWD when that was given
	if repo == "" {
		return grant
	}
	held := map[SessionID][]string{}
	for _, c := range s.claims {
		if c.Owner != id && c.Repo == repo && s.valid(c, now) {
			held[c.Owner] = append(held[c.Owner], c.Path)
		}
	}
	if len(held) == 0 {
		return grant
	}
	hs := s.holders(held, now)
	return proto.Response{OK: true, Decision: proto.Deny, Holders: hs, Reason: guardReason(hs, risk, repo)}
}

func (s *State) release(id SessionID, req proto.Request) proto.Response {
	if req.All {
		for p, c := range s.claims {
			if c.Owner == id {
				delete(s.claims, p)
			}
		}
	}
	for _, p := range cleanPaths(req.Paths) {
		if c := s.claims[p]; c != nil && c.Owner == id {
			delete(s.claims, p)
		}
	}
	return proto.Response{OK: true}
}

func (s *State) check(id SessionID, req proto.Request, now time.Time) proto.Response {
	held := map[SessionID][]string{}
	for _, p := range cleanPaths(req.Paths) {
		if c := s.claims[p]; c != nil && c.Owner != id && s.valid(c, now) {
			held[c.Owner] = append(held[c.Owner], p)
		}
	}
	if len(held) == 0 {
		return proto.Response{OK: true, Decision: proto.Grant}
	}
	hs := s.holders(held, now)
	return proto.Response{OK: true, Decision: proto.Deny, Holders: hs, Reason: heldReason(hs,
		"has uncommitted work by", "have uncommitted work by", "the files below have uncommitted work by",
		"Leave this file out of your commit, or ask the user how to proceed.",
		"Leave these files out of your commit, or ask the user how to proceed.")}
}

func (s *State) status(now time.Time) proto.Response {
	s.prune(now)
	var out []proto.Holder
	for _, sess := range s.sessions {
		out = append(out, s.holder(sess, s.pathsOf(sess.ID), now))
	}
	sortHolders(out)
	return proto.Response{OK: true, Sessions: out}
}

// ---- sessions and claims ----

// touch upserts the requesting session and marks it seen.
func (s *State) touch(id SessionID, req proto.Request, now time.Time) *Session {
	sess := s.sessions[id]
	if sess == nil {
		sess = &Session{ID: id, StartedAt: now}
		s.sessions[id] = sess
	}
	sess.LastSeen = now
	if req.Agent != "" {
		sess.Agent = req.Agent
	}
	if req.PID > 0 {
		sess.PID = req.PID
	}
	if req.CWD != "" {
		sess.CWD = req.CWD
		sess.Repo = s.env.RepoRoot(req.CWD)
	}
	return sess
}

// drop removes a session and all its claims.
func (s *State) drop(id SessionID) {
	delete(s.sessions, id)
	for p, c := range s.claims {
		if c.Owner == id {
			delete(s.claims, p)
		}
	}
}

// live returns the session if it exists and is alive. A dead session is
// removed together with its claims.
func (s *State) live(id SessionID, now time.Time) *Session {
	sess := s.sessions[id]
	if sess == nil {
		return nil
	}
	var alive bool
	if sess.PID > 0 {
		alive = s.env.Alive(sess.PID)
	} else {
		alive = now.Sub(sess.LastSeen) < s.cfg.IdleTTL
	}
	if !alive {
		s.drop(id)
		return nil
	}
	return sess
}

// valid applies the rule of docs/DESIGN.md section 6 and deletes the claim
// when it no longer holds. The grace check comes before Dirty because Dirty
// runs git.
func (s *State) valid(c *Claim, now time.Time) bool {
	ok := s.live(c.Owner, now) != nil
	if ok && c.Repo != "" && now.Sub(c.TouchedAt) >= s.cfg.Grace {
		dirty, known := s.env.Dirty(c.Repo, c.Path)
		ok = !known || dirty
	}
	if !ok {
		delete(s.claims, c.Path)
	}
	return ok
}

// prune removes dead sessions and invalid claims.
func (s *State) prune(now time.Time) {
	for id := range s.sessions {
		s.live(id, now)
	}
	for _, c := range s.claims {
		s.valid(c, now)
	}
}

// pathsOf returns the sorted paths claimed by id. Call after prune.
func (s *State) pathsOf(id SessionID) []string {
	var out []string
	for p, c := range s.claims {
		if c.Owner == id {
			out = append(out, p)
		}
	}
	gslice.Sort(out)
	return out
}

func (s *State) holder(sess *Session, paths []string, now time.Time) proto.Holder {
	idle := int(now.Sub(sess.LastSeen) / time.Second)
	if idle < 0 {
		idle = 0
	}
	return proto.Holder{
		Session: string(sess.ID),
		Agent:   sess.Agent,
		PID:     sess.PID,
		CWD:     sess.CWD,
		Repo:    sess.Repo,
		Note:    sess.Note,
		IdleS:   idle,
		Paths:   paths,
	}
}

// holders turns owner -> paths into Holders sorted by session id.
func (s *State) holders(byOwner map[SessionID][]string, now time.Time) []proto.Holder {
	var out []proto.Holder
	for id, paths := range byOwner {
		sess := s.sessions[id]
		if sess == nil {
			continue
		}
		gslice.Sort(paths)
		out = append(out, s.holder(sess, paths, now))
	}
	sortHolders(out)
	return out
}

func sortHolders(hs []proto.Holder) {
	gslice.SortBy(hs, func(a, b proto.Holder) bool { return a.Session < b.Session })
}

// cleanPaths normalises and de-duplicates request paths. This is the one
// place paths are normalised; symlinks are resolved by the client.
func cleanPaths(in []string) []string {
	nonEmpty := gslice.Filter(in, func(p string) bool { return p != "" })
	return gslice.Uniq(gslice.Map(nonEmpty, filepath.Clean))
}

// cleanNote collapses whitespace (newlines included) to single spaces and
// keeps the first 80 runes.
func cleanNote(n string) string {
	n = strings.Join(strings.Fields(n), " ")
	return strings.TrimSpace(firstRunes(n, noteMaxRunes))
}

func firstRunes(s string, n int) string {
	if utf8.RuneCountInString(s) <= n {
		return s
	}
	return string([]rune(s)[:n])
}

// ---- text written for the model ----

func ago(sec int) string {
	switch {
	case sec < 60:
		return fmt.Sprintf("%ds", sec)
	case sec < 3600:
		return fmt.Sprintf("%dm", sec/60)
	case sec < 86400:
		return fmt.Sprintf("%dh", sec/3600)
	}
	return fmt.Sprintf("%dd", sec/86400)
}

// describe renders a holder as `claude:9f2c, active 40s ago, working on "refactor token refresh"`.
func describe(h proto.Holder) string {
	d := fmt.Sprintf("%s, active %s ago", h.Session, ago(h.IdleS))
	if h.Note != "" {
		d += fmt.Sprintf(", working on %q", h.Note)
	}
	return d
}

// pathList joins up to limit paths and appends "and N more" for the rest.
func pathList(paths []string, limit int) string {
	if len(paths) <= limit {
		return strings.Join(paths, ", ")
	}
	more := fmt.Sprintf("and %d more", len(paths)-limit)
	if limit <= 0 {
		return more
	}
	return strings.Join(paths[:limit], ", ") + " " + more
}

// heldReason builds the deny text for claim and check.
func heldReason(hs []proto.Holder, verb1, verbN, verbMulti, advice1, adviceN string) string {
	if len(hs) == 1 {
		h := hs[0]
		verb, advice := verb1, advice1
		if len(h.Paths) > 1 {
			verb, advice = verbN, adviceN
		}
		return fmt.Sprintf("agent-quorum: %s %s by another agent session (%s). %s",
			pathList(h.Paths, reasonMaxFiles), verb, describe(h), advice)
	}
	parts := make([]string, 0, len(hs))
	left := reasonMaxFiles
	for _, h := range hs {
		n := min(len(h.Paths), max(left, 1))
		left -= n
		parts = append(parts, fmt.Sprintf("%s (%s)", pathList(h.Paths, n), describe(h)))
	}
	return fmt.Sprintf("agent-quorum: %s other agent sessions: %s. %s", verbMulti, strings.Join(parts, "; "), adviceN)
}

func guardReason(hs []proto.Holder, risk guard.Risk, repo string) string {
	parts := make([]string, 0, len(hs))
	left := reasonMaxFiles
	for _, h := range hs {
		n := min(len(h.Paths), max(left, 1))
		left -= n
		parts = append(parts, fmt.Sprintf("%s (%s) holds %s", h.Session, describe(h)[len(h.Session)+2:], pathList(h.Paths, n)))
	}
	who := "another agent session has"
	if len(hs) > 1 {
		who = "other agent sessions have"
	}
	advice := "So do not run this command; it would overwrite or hide another session's uncommitted work. Ask the user how to proceed."
	if risk == guard.SweepsIndex {
		advice = "This command would stage or commit their files. Instead, stage only your own files by explicit path: git add <paths>, and commit without -a."
	}
	return fmt.Sprintf("agent-quorum: command blocked, %s uncommitted work in %s: %s. %s",
		who, repo, strings.Join(parts, "; "), advice)
}

const (
	contextHead = "agent-quorum: other agent sessions are working in this repository right now:\n"
	contextTail = "Edits to files held by another session will be denied by agent-quorum. " +
		"Do not work around a denial with shell commands (sed, redirection, etc.). " +
		"Stage files by explicit path (git add <paths>), never git add -A or git commit -a. " +
		"Avoid tree-wide git commands (checkout, stash, reset --hard)."
)

// peerContext is the text injected into a new session that has peers. It
// never exceeds contextMax characters: detail is reduced level by level,
// then trailing sessions are folded into "and N more sessions".
func peerContext(peers []proto.Holder, repo string) string {
	if len(peers) == 0 {
		return ""
	}
	budget := contextMax - utf8.RuneCountInString(contextHead) - utf8.RuneCountInString(contextTail)
	levels := []struct{ files, note int }{{3, 80}, {2, 40}, {1, 20}, {0, 0}}

	var lines []string
	for _, lv := range levels {
		lines = lines[:0]
		total := 0
		for _, p := range peers {
			l := peerLine(p, repo, lv.files, lv.note)
			total += utf8.RuneCountInString(l)
			lines = append(lines, l)
		}
		if total <= budget {
			return contextHead + strings.Join(lines, "") + contextTail
		}
	}
	// Still too long at the tersest level: keep as many sessions as fit.
	for keep := len(lines) - 1; keep >= 0; keep-- {
		body := strings.Join(lines[:keep], "") + fmt.Sprintf("- and %d more sessions\n", len(lines)-keep)
		if utf8.RuneCountInString(body) <= budget {
			return contextHead + body + contextTail
		}
	}
	return firstRunes(contextHead+contextTail, contextMax)
}

func peerLine(p proto.Holder, repo string, files, note int) string {
	l := "- " + p.Session
	if n := firstRunes(p.Note, note); n != "" {
		l += fmt.Sprintf(" (%q)", n)
	}
	switch {
	case len(p.Paths) == 0:
		l += ": no files held yet"
	case files == 0:
		l += fmt.Sprintf(" holds %d files", len(p.Paths))
	default:
		rel := gslice.Map(p.Paths, func(path string) string {
			if repo == "" {
				return path
			}
			return strings.TrimPrefix(path, repo+string(filepath.Separator))
		})
		l += " holds " + pathList(rel, files)
	}
	return l + "\n"
}

// ---- snapshot ----

type snapshot struct {
	V        int       `json:"v"`
	Sessions []Session `json:"sessions"`
	Claims   []Claim   `json:"claims"`
}

// Export returns a JSON snapshot of all sessions and claims.
func (s *State) Export() ([]byte, error) {
	s.mu.Lock()
	defer s.mu.Unlock()

	snap := snapshot{V: 1, Sessions: []Session{}, Claims: []Claim{}}
	for _, sess := range s.sessions {
		snap.Sessions = append(snap.Sessions, *sess)
	}
	for _, c := range s.claims {
		snap.Claims = append(snap.Claims, *c)
	}
	gslice.SortBy(snap.Sessions, func(a, b Session) bool { return a.ID < b.ID })
	gslice.SortBy(snap.Claims, func(a, b Claim) bool { return a.Path < b.Path })
	return sonic.ConfigStd.Marshal(snap)
}

// Import replaces the state with a snapshot from Export. Empty data is a
// no-op; on error the state is left unchanged.
func (s *State) Import(data []byte) error {
	if len(data) == 0 {
		return nil
	}
	var snap snapshot
	if err := sonic.ConfigStd.Unmarshal(data, &snap); err != nil {
		return fmt.Errorf("core: import snapshot: %w", err)
	}
	sessions := make(map[SessionID]*Session, len(snap.Sessions))
	for i := range snap.Sessions {
		if sess := &snap.Sessions[i]; sess.ID != "" {
			sessions[sess.ID] = sess
		}
	}
	claims := make(map[string]*Claim, len(snap.Claims))
	for i := range snap.Claims {
		if c := &snap.Claims[i]; c.Path != "" {
			claims[c.Path] = c
		}
	}

	s.mu.Lock()
	defer s.mu.Unlock()
	s.sessions, s.claims = sessions, claims
	return nil
}
